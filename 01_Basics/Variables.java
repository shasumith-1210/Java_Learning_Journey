public class Variables {
    public static void main(String[] args) {
        int age = 19;
        double cgpa = 9.25;
        char grade = 'A';
        boolean passed = true;

        System.out.println("Age    : " + age);
        System.out.println("CGPA   : " + cgpa);
        System.out.println("Grade  : " + grade);
        System.out.println("Passed : " + passed);
    }
}
